"""Extract the supplied CASIO CW01 key outlines for the PLUS keylog.

Requires fontTools. The original TTF/PDF remain in docs/keymaps/.
SVG and canvas use the same unmodified outlines; no system font is needed.
"""
from pathlib import Path
from hashlib import sha256
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/keymaps/casio-classwiz-cw01'
mapping = json.loads((SOURCE / 'plus-keymap.json').read_text())
font_path = SOURCE / 'CASIO ClassWiz CW01.ttf'
assert sha256(font_path.read_bytes()).hexdigest() == mapping['source']['fontSha256']
font = TTFont(font_path)
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
outlines = {}
for entry in mapping['mapping']:
    char = entry['character']
    name = cmap[ord(char)]
    path = SVGPathPen(glyph_set)
    bounds = BoundsPen(glyph_set)
    glyph_set[name].draw(path)
    glyph_set[name].draw(bounds)
    assert path.getCommands() and bounds.bounds
    outlines[char] = {'bounds': bounds.bounds, 'path': path.getCommands()}
assert len(outlines) == 48
output = ROOT / 'web/assets/keylog-glyphs-880.js'
output.write_text(
    "// Generated by tools/build-keylog-glyphs.py from CASIO ClassWiz CW01 Ver.1.00.\n"
    "// Original outlines, including the key outlines; copyright CASIO, 2022.\n"
    "// Source TTF SHA-256: " + mapping['source']['fontSha256'] + "\n"
    "'use strict';\nconst KEYLOG_GLYPHS_880 = Object.freeze(" +
    json.dumps(outlines, separators=(',', ':'), ensure_ascii=True) + ");\n"
    "if (typeof module==='object' && module.exports) module.exports=KEYLOG_GLYPHS_880;\n"
)
print(json.dumps({'asset': str(output), 'glyphs': len(outlines),
                  'bytes': output.stat().st_size, 'sha256': sha256(output.read_bytes()).hexdigest()}))
